#!/usr/bin/env node
/**
 * `npm run stack:init`: keys and pins for the Docker Compose stack (compose.yaml), FICTIONAL data only.
 *
 *   1. deletes .stack/keys and writes fresh demo secrets there (the same set as demo:reset, scripts/demo-lib.mjs)
 *   2. writes .stack/stack.env: the public pins, which compose.yaml bakes into the web build and hands to each service
 *
 * Each container mounts only its own secrets (compose.yaml `secrets:`), so key holder 2 never sees share 1. On one
 * machine the dealer still had every file for a moment; between real institutions each share file goes to a different
 * organization and the pooled copy is deleted (docs/ops/MULTI_PARTY_DEPLOY.md). Run `npm run stack:reset` to also
 * delete the Docker volumes and start from an empty, re-seeded stack.
 */
import fs from 'node:fs';
import path from 'node:path';
import { ROOT, generateKeys } from './demo-lib.mjs';

const STACK = path.join(ROOT, '.stack');
const KEYS = path.join(STACK, 'keys');

if (process.env.NODE_ENV === 'production') throw new Error('stack:init makes demo keys and refuses NODE_ENV=production.');
fs.rmSync(KEYS, { recursive: true, force: true });
fs.mkdirSync(KEYS, { recursive: true, mode: 0o700 });

// The ceremony refuses to write into the database directory; point it somewhere that is not KEYS.
const pub = await generateKeys(KEYS, { ...process.env, MATRA_DB_PATH: path.join(STACK, 'none', 'matra.db') });
// Docker Desktop bind-mounts secrets with the host file's mode, and the containers run as `node`, not as you.
for (const f of fs.readdirSync(KEYS)) fs.chmodSync(path.join(KEYS, f), 0o644);
fs.chmodSync(KEYS, 0o755);

const env = {
  MATRA_OPRF_THRESHOLD: pub.t,
  MATRA_OPRF_HOLDERS: pub.m,
  MATRA_OPRF_GROUP_PUBKEY: pub.groupPublicKey,
  MATRA_OPRF_SHARE_PUBKEYS: pub.holders.map((h) => h.publicKey).join(','),
  MATRA_HOLDER_TOKEN_PUBKEY: pub.holderTokenPublicKey,
  MATRA_COUNSELOR_ROSTER_PUBKEY: pub.rosterPublicKey,
  MATRA_ATTESTATION_PLATFORM_PUBKEY: pub.platformPublicKey,
  MATRA_MATCHER_MEASUREMENT: pub.measurement,
};
fs.writeFileSync(
  path.join(STACK, 'stack.env'),
  `# Generated by npm run stack:init (${pub.createdAt}). Public pins only; the secrets are in .stack/keys.\n` +
    Object.entries(env).map(([k, v]) => `${k}=${v}`).join('\n') + '\n',
);
fs.writeFileSync(path.join(KEYS, 'public.json'), JSON.stringify(pub, null, 2));
console.log(`[stack:init] ${pub.t}-of-${pub.m} OPRF, matcher measurement ${pub.measurement.slice(0, 16)}…`);
console.log('[stack:init] next: npm run stack:up');
