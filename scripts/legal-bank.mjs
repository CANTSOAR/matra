#!/usr/bin/env node
// Legal question bank helper. See docs/legal-research/README.md.
//
//   npm run legal -- new "Question title" [--area matching] [--priority P1] [--source "interview 2026-11-10"]
//   npm run legal -- index     regenerate docs/legal-research/INDEX.md from the question files
//   npm run legal -- check     validate every question file's front matter

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const bank = path.join(root, 'docs/legal-research');
const qdir = path.join(bank, 'questions');

const STATUSES = ['open', 'researching', 'memo-ready', 'asked', 'answered', 'parked', 'merged'];
const PRIORITIES = ['P0', 'P1', 'P2'];
const REQUIRED = ['id', 'title', 'status', 'priority', 'area', 'jurisdiction', 'source', 'blocks'];

function parse(file) {
  const text = fs.readFileSync(file, 'utf8');
  const m = text.match(/^---\n([\s\S]*?)\n---/);
  const meta = {};
  if (m) {
    for (const line of m[1].split('\n')) {
      const i = line.indexOf(':');
      if (i > 0) meta[line.slice(0, i).trim()] = line.slice(i + 1).trim();
    }
  }
  return { file, meta };
}

function questions() {
  return fs
    .readdirSync(qdir)
    .filter((f) => /^Q-\d{3,}.*\.md$/.test(f))
    .sort()
    .map((f) => parse(path.join(qdir, f)));
}

function slugify(s) {
  return s.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '').slice(0, 60);
}

function arg(args, name, fallback) {
  const i = args.indexOf(`--${name}`);
  return i >= 0 && args[i + 1] ? args[i + 1] : fallback;
}

function cmdNew(args) {
  const title = args.find((a, i) => !a.startsWith('--') && !(i > 0 && args[i - 1].startsWith('--')));
  if (!title) throw new Error('usage: npm run legal -- new "Question title" [--area x] [--priority P1] [--source y]');
  const template = fs.readFileSync(path.join(bank, 'TEMPLATE.md'), 'utf8');
  const today = new Date().toISOString().slice(0, 10);
  // Allocate the next free ID. mkdir of a reservation dir is atomic, so parallel sessions never share an ID.
  const ids = path.join(qdir, '.ids');
  fs.mkdirSync(ids, { recursive: true });
  let n = Math.max(0, ...questions().map((q) => Number(q.meta.id?.slice(2)) || 0)) + 1;
  for (;; n++) {
    const id = `Q-${String(n).padStart(3, '0')}`;
    try {
      fs.mkdirSync(path.join(ids, id));
    } catch (e) {
      if (e.code === 'EEXIST') continue;
      throw e;
    }
    if (fs.readdirSync(qdir).some((f) => f.startsWith(`${id}-`))) continue;
    const file = path.join(qdir, `${id}-${slugify(title)}.md`);
    const body = template
      .replace('id: Q-000', `id: ${id}`)
      .replace('title: ', `title: ${title}`)
      .replace('priority: P1', `priority: ${arg(args, 'priority', 'P1')}`)
      .replace('area: ', `area: ${arg(args, 'area', '')}`)
      .replace('source: ', `source: ${arg(args, 'source', `added ${today}`)}`)
      .replace('created: ', `created: ${today}`);
    fs.writeFileSync(file, body, { flag: 'wx' });
    console.log(path.relative(root, file));
    return;
  }
}

function problems() {
  const out = [];
  const ids = new Set();
  for (const { file, meta } of questions()) {
    const name = path.basename(file);
    for (const k of REQUIRED) if (!meta[k]) out.push(`${name}: missing ${k}`);
    if (meta.id && !name.startsWith(`${meta.id}-`)) out.push(`${name}: id ${meta.id} does not match file name`);
    if (ids.has(meta.id)) out.push(`${name}: duplicate id ${meta.id}`);
    ids.add(meta.id);
    if (meta.status && !STATUSES.includes(meta.status)) out.push(`${name}: status must be one of ${STATUSES.join(', ')}`);
    if (meta.priority && !PRIORITIES.includes(meta.priority)) out.push(`${name}: priority must be one of ${PRIORITIES.join(', ')}`);
    if (meta.status === 'answered' && !meta.decision) out.push(`${name}: answered needs decision: D-### (a DECISIONS.md entry)`);
    if (meta.status === 'merged' && !meta.merged_into) out.push(`${name}: merged needs merged_into: Q-###`);
  }
  return out;
}

function cmdIndex() {
  const qs = questions();
  const rank = (q) => [STATUSES.indexOf(q.meta.status), PRIORITIES.indexOf(q.meta.priority), q.meta.id];
  qs.sort((a, b) => {
    const [x, y] = [rank(a), rank(b)];
    return x[0] - y[0] || x[1] - y[1] || String(x[2]).localeCompare(String(y[2]));
  });
  const counts = STATUSES.map((s) => `${s} ${qs.filter((q) => q.meta.status === s).length}`).join(' · ');
  const lines = [
    '# Legal question index',
    '',
    '*Generated by `npm run legal -- index`. Do not edit by hand; edit the question files.*',
    '',
    `${qs.length} questions: ${counts}`,
    '',
  ];
  for (const status of STATUSES) {
    const group = qs.filter((q) => q.meta.status === status);
    if (!group.length) continue;
    lines.push(`## ${status}`, '', '| ID | P | Area | Question | Blocks |', '|---|---|---|---|---|');
    for (const { file, meta } of group) {
      const link = `[${meta.title.replace(/\|/g, '\\|')}](questions/${path.basename(file)})`;
      const extra = meta.merged_into ? ` → ${meta.merged_into}` : meta.decision ? ` (${meta.decision})` : '';
      lines.push(`| ${meta.id} | ${meta.priority} | ${meta.area} | ${link}${extra} | ${(meta.blocks || '').replace(/\|/g, '\\|')} |`);
    }
    lines.push('');
  }
  const issues = problems();
  if (issues.length) lines.push('## Front-matter problems', '', ...issues.map((p) => `- ${p}`), '');
  fs.writeFileSync(path.join(bank, 'INDEX.md'), lines.join('\n'));
  console.log(`INDEX.md: ${qs.length} questions${issues.length ? `, ${issues.length} problems` : ''}`);
}

function cmdCheck() {
  const issues = problems();
  for (const p of issues) console.log(p);
  console.log(issues.length ? `${issues.length} problems` : `ok (${questions().length} questions)`);
  process.exitCode = issues.length ? 1 : 0;
}

const [cmd, ...rest] = process.argv.slice(2);
const commands = { new: cmdNew, index: cmdIndex, check: cmdCheck };
if (commands[cmd]) commands[cmd](rest);
else console.log('usage: npm run legal -- new "title" | index | check');
